//! Generates the root `Cargo.toml` and `.cargo/config.toml` from upstream plus Neutron's overlay.

use crate::layout::Layout;
use crate::upstream::Upstream;
use anyhow::{Context as _, Result};
use toml_edit::{DocumentMut, Item, Table, Value};

pub struct Overlay {
    document: DocumentMut,
}

impl Overlay {
    pub fn parse(text: &str) -> Result<Self> {
        let document = text
            .parse::<DocumentMut>()
            .context("parsing neutron.workspace.toml")?;
        Ok(Self { document })
    }

    fn section(&self, name: &str) -> Option<&Table> {
        self.document.get(name).and_then(Item::as_table)
    }
}

pub fn root_manifest(
    upstream: &Upstream,
    layout: &Layout,
    overlay: &Overlay,
    warnings: &mut Vec<String>,
) -> Result<String> {
    let text = String::from_utf8(upstream.read("Cargo.toml")?)
        .context("upstream Cargo.toml is not UTF-8")?;
    let mut document = text
        .parse::<DocumentMut>()
        .context("parsing upstream Cargo.toml")?;

    if let Some(workspace) = document.get_mut("workspace").and_then(Item::as_table_mut) {
        for key in ["members", "default-members", "exclude"] {
            if let Some(array) = workspace.get_mut(key).and_then(Item::as_array_mut) {
                array.retain(|entry| match entry.as_str() {
                    Some(path) if layout.map(path).is_none() => {
                        warnings.push(format!(
                            "workspace.{key} entry `{path}` is excluded by upstream.toml"
                        ));
                        false
                    }
                    _ => true,
                });
                for entry in array.iter_mut() {
                    remap_value(entry, layout);
                }
            }
        }
    }
    remap_path_keys(document.as_table_mut(), layout);

    if let Some(section) = overlay.section("manifest") {
        merge_table(document.as_table_mut(), section);
    }

    Ok(format!(
        "# GENERATED by `cargo neutron sync` from upstream Zed (the commit is in upstream.toml).\n\
         # Do not edit: add Neutron-specific entries to neutron.workspace.toml instead.\n\n{document}"
    ))
}

pub fn cargo_config(upstream: &Upstream, overlay: &Overlay) -> Result<String> {
    let text = String::from_utf8(upstream.read(".cargo/config.toml")?)
        .context("upstream .cargo/config.toml is not UTF-8")?;
    let mut document = text
        .parse::<DocumentMut>()
        .context("parsing upstream .cargo/config.toml")?;
    if let Some(section) = overlay.section("cargo-config") {
        merge_table(document.as_table_mut(), section);
    }
    Ok(format!(
        "# GENERATED by `cargo neutron sync` from upstream Zed (the commit is in upstream.toml).\n\
         # Do not edit: add entries to the [cargo-config] section of neutron.workspace.toml instead.\n\n{document}"
    ))
}

fn remap_value(value: &mut Value, layout: &Layout) {
    let Some(path) = value.as_str() else {
        return;
    };
    let Some(mapped) = layout.map(path) else {
        return;
    };
    if mapped.path != path {
        let decor = value.decor().clone();
        *value = Value::from(mapped.path);
        *value.decor_mut() = decor;
    }
}

/// Remaps every `path = "..."` in the manifest: workspace dependencies, patches, dylint libraries.
fn remap_path_keys(table: &mut Table, layout: &Layout) {
    for (key, item) in table.iter_mut() {
        // A dependency can itself be named `path`, so only string values are paths.
        if key.get() == "path" && item.is_str() {
            if let Some(value) = item.as_value_mut() {
                remap_value(value, layout);
            }
        } else {
            remap_item(item, layout);
        }
    }
}

fn remap_item(item: &mut Item, layout: &Layout) {
    match item {
        Item::Table(table) => remap_path_keys(table, layout),
        Item::ArrayOfTables(tables) => {
            for table in tables.iter_mut() {
                remap_path_keys(table, layout);
            }
        }
        Item::Value(value) => remap_nested_value(value, layout),
        Item::None => {}
    }
}

fn remap_nested_value(value: &mut Value, layout: &Layout) {
    match value {
        Value::InlineTable(table) => {
            for (key, value) in table.iter_mut() {
                if key.get() == "path" && value.is_str() {
                    remap_value(value, layout);
                } else {
                    remap_nested_value(value, layout);
                }
            }
        }
        Value::Array(array) => {
            for value in array.iter_mut() {
                remap_nested_value(value, layout);
            }
        }
        _ => {}
    }
}

/// Merges `overlay` into `target`: tables merge recursively, arrays are extended with entries
/// they do not have yet, and every other value replaces the upstream one.
fn merge_table(target: &mut Table, overlay: &Table) {
    for (key, overlay_item) in overlay.iter() {
        match target.get_mut(key) {
            Some(target_item) => merge_item(target_item, overlay_item),
            None => {
                target.insert(key, overlay_item.clone());
            }
        }
    }
}

fn merge_item(target: &mut Item, overlay: &Item) {
    match (target, overlay) {
        (Item::Table(target), Item::Table(overlay)) => merge_table(target, overlay),
        (Item::Value(Value::Array(target)), Item::Value(Value::Array(overlay))) => {
            for value in overlay.iter() {
                let rendered = value.to_string();
                let already_present = target
                    .iter()
                    .any(|existing| existing.to_string().trim() == rendered.trim());
                if !already_present {
                    // Lay new entries out like the last existing one (upstream puts one per line).
                    let decor = target.iter().last().map(|last| last.decor().clone());
                    target.push(value.clone());
                    if let (Some(decor), Some(pushed)) = (decor, target.iter_mut().last()) {
                        *pushed.decor_mut() = decor;
                    }
                }
            }
        }
        (Item::Value(Value::InlineTable(target)), Item::Value(Value::InlineTable(overlay))) => {
            for (key, value) in overlay.iter() {
                target.insert(key, value.clone());
            }
        }
        (target, overlay) => *target = overlay.clone(),
    }
}
