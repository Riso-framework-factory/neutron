use crate::agents;
use crate::config::{CONFIG_FILE, Config, OVERLAY_FILE};
use crate::layout::{Destination, Layout, strip_path_prefix};
use crate::manifest::{self, Overlay};
use crate::rewrite::{PathFixer, Rewrite};
use crate::upstream::{FileKind, Upstream};
use crate::{lockfile, shim};
use anyhow::{Context as _, Result, bail};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;
use walkdir::WalkDir;

/// Directories and files inside managed roots that the sync never deletes.
const PRESERVED_NAMES: &[&str] = &["target", "node_modules", ".DS_Store"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Entry {
    File { content: Vec<u8>, executable: bool },
    Symlink { target: String },
}

struct PlannedEntry {
    entry: Entry,
    /// `None` for files generated by Neutron itself.
    destination: Option<Destination>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ChangeKind {
    Write,
    Delete,
}

#[derive(Debug, Clone)]
pub struct Change {
    pub path: String,
    pub kind: ChangeKind,
    pub destination: Option<Destination>,
}

pub struct SyncOutcome {
    pub changes: Vec<Change>,
    pub rewrites: Vec<Rewrite>,
    pub warnings: Vec<String>,
    /// Shim files left with conflict markers or needing a decision.
    pub conflicts: Vec<String>,
}

pub fn run(
    root: &Path,
    config: &Config,
    upstream: &Upstream,
    layout: &Layout,
    dry_run: bool,
) -> Result<SyncOutcome> {
    let mut warnings = crate_changes_since(upstream, layout, &config.upstream.commit)?;
    let mut rewrites = Vec::new();
    let mut plan: BTreeMap<String, PlannedEntry> = BTreeMap::new();
    let fixer = PathFixer::new(upstream, layout, &config.rewrite.literals);

    for file in &upstream.files {
        if layout.is_unmanaged(&file.path) {
            continue;
        }
        let Some(mapped) = layout.map(&file.path) else {
            continue;
        };
        if mapped.destination == Destination::Shim {
            continue;
        }
        let entry = match file.kind {
            FileKind::Symlink => {
                let target = upstream.read_link(&file.path)?;
                let target = match mapped.destination {
                    Destination::Core => target,
                    Destination::Root | Destination::Ide | Destination::Shim => {
                        fixer.fix_symlink(&file.path, &target).unwrap_or(target)
                    }
                };
                Entry::Symlink { target }
            }
            FileKind::Regular | FileKind::Executable => {
                let mut content = upstream.read(&file.path)?;
                if mapped.destination != Destination::Core
                    && PathFixer::applies_to(&file.path)
                    && let Ok(text) = std::str::from_utf8(&content)
                {
                    let (fixed, file_rewrites) = fixer.fix_source(&file.path, text);
                    if !file_rewrites.is_empty() {
                        content = fixed.into_bytes();
                        rewrites.extend(file_rewrites);
                    }
                }
                Entry::File {
                    content,
                    executable: file.kind == FileKind::Executable,
                }
            }
        };
        add_entry(&mut plan, mapped.path, entry, Some(mapped.destination))?;
    }

    let overlay_text = fs::read_to_string(root.join(OVERLAY_FILE))
        .with_context(|| format!("reading {OVERLAY_FILE}"))?;
    let overlay = Overlay::parse(&overlay_text)?;
    let generated = [
        (
            "Cargo.toml".to_string(),
            manifest::root_manifest(upstream, layout, &overlay, &mut warnings)?.into_bytes(),
        ),
        (
            ".cargo/config.toml".to_string(),
            manifest::cargo_config(upstream, &overlay)?.into_bytes(),
        ),
        (
            format!("{}/AGENTS.md", layout.ide_root()),
            agents::ide_notice(upstream).into_bytes(),
        ),
    ];
    for (path, content) in generated {
        add_entry(
            &mut plan,
            path,
            Entry::File {
                content,
                executable: false,
            },
            None,
        )?;
    }

    let agents_path = root.join("AGENTS.md");
    let existing_agents = fs::read_to_string(&agents_path).context("reading AGENTS.md")?;
    let agents = agents::root_agents(
        &existing_agents,
        upstream,
        layout,
        &config.agents.sections,
        &config.agents.drop_lines_containing,
        &mut warnings,
    )?;
    add_entry(
        &mut plan,
        "AGENTS.md".to_string(),
        Entry::File {
            content: agents.into_bytes(),
            executable: false,
        },
        None,
    )?;
    for (path, content) in
        agents::skill_files(upstream, layout, &config.agents.skills, &mut warnings)?
    {
        add_entry(
            &mut plan,
            path,
            Entry::File {
                content,
                executable: false,
            },
            None,
        )?;
    }

    let mut managed_roots = layout.managed_roots();
    managed_roots.extend(
        config
            .agents
            .skills
            .iter()
            .map(|skill| format!(".agents/skills/{skill}")),
    );
    for protected in [CONFIG_FILE, OVERLAY_FILE] {
        if managed_roots
            .iter()
            .any(|managed| strip_path_prefix(protected, managed).is_some())
        {
            bail!("{protected} must not be inside a directory managed by the sync");
        }
    }

    let mut changes = Vec::new();
    for (path, planned) in &plan {
        if needs_write(&root.join(path), &planned.entry)? {
            changes.push(Change {
                path: path.clone(),
                kind: ChangeKind::Write,
                destination: planned.destination,
            });
            if !dry_run {
                write_entry(&root.join(path), &planned.entry)?;
            }
        }
    }
    for stale in stale_paths(root, &managed_roots, &plan)? {
        if !dry_run {
            let full_path = root.join(&stale);
            fs::remove_file(&full_path)
                .with_context(|| format!("deleting {}", full_path.display()))?;
        }
        let destination = layout.map_neutron_destination(&stale);
        changes.push(Change {
            path: stale,
            kind: ChangeKind::Delete,
            destination,
        });
    }
    if !dry_run {
        for managed in &managed_roots {
            remove_empty_directories(&root.join(managed))?;
        }
    }

    let mut conflicts = Vec::new();
    for (name, shim_config) in &config.shim {
        let merged = shim::merge(root, upstream, name, shim_config, dry_run)?;
        changes.extend(merged.changes);
        conflicts.extend(merged.conflicts);
        if !dry_run && let Some(new_base) = merged.new_base {
            Config::record_shim_base(root, name, &new_base)?;
        }
    }

    // Last, because the root manifest and shim manifests decide which members the lock holds.
    if lockfile::sync(root, upstream, dry_run)? {
        changes.push(Change {
            path: "Cargo.lock".to_string(),
            kind: ChangeKind::Write,
            destination: None,
        });
    }

    Ok(SyncOutcome {
        changes,
        rewrites,
        warnings,
        conflicts,
    })
}

/// Upstream crates added or removed since the previously synced commit. New crates land in the
/// IDE mirror by default, so someone has to decide whether they belong in core.
fn crate_changes_since(
    upstream: &Upstream,
    layout: &Layout,
    previous: &str,
) -> Result<Vec<String>> {
    if previous.is_empty() || previous == upstream.commit {
        return Ok(Vec::new());
    }
    // An unknown previous commit (for example after a force-push upstream) just skips the report.
    let Ok(previous_files) = upstream.files_at(previous, ".") else {
        return Ok(Vec::new());
    };
    let previous_directories: BTreeSet<&str> = previous_files
        .iter()
        .filter_map(|path| path.strip_suffix("/Cargo.toml"))
        .collect();
    let current_directories: BTreeSet<&str> = upstream
        .packages
        .iter()
        .map(|package| package.dir.as_str())
        .collect();

    let mut notes = Vec::new();
    for directory in current_directories.difference(&previous_directories) {
        let destination = layout
            .map(directory)
            .map_or_else(|| "nowhere (excluded)".to_string(), |mapped| mapped.path);
        notes.push(format!(
            "new upstream crate `{directory}` was mirrored to `{destination}`; classify it in upstream.toml"
        ));
    }
    for directory in previous_directories.difference(&current_directories) {
        // Only workspace packages count; nested fixtures and benchmarks also have a Cargo.toml.
        if upstream.exists(directory) {
            continue;
        }
        notes.push(format!(
            "upstream crate `{directory}` was removed; drop it from upstream.toml if it is listed there"
        ));
    }
    Ok(notes)
}

fn add_entry(
    plan: &mut BTreeMap<String, PlannedEntry>,
    path: String,
    entry: Entry,
    destination: Option<Destination>,
) -> Result<()> {
    if plan.contains_key(&path) {
        bail!("two upstream paths map to {path}; fix upstream.toml");
    }
    plan.insert(path, PlannedEntry { entry, destination });
    Ok(())
}

pub fn needs_write(path: &Path, entry: &Entry) -> Result<bool> {
    let Ok(metadata) = fs::symlink_metadata(path) else {
        return Ok(true);
    };
    match entry {
        Entry::Symlink { target } => {
            if !metadata.file_type().is_symlink() {
                return Ok(true);
            }
            let current = fs::read_link(path)
                .with_context(|| format!("reading symlink {}", path.display()))?;
            Ok(current.to_str() != Some(target.as_str()))
        }
        Entry::File {
            content,
            executable,
        } => {
            if !metadata.file_type().is_file() {
                return Ok(true);
            }
            if is_executable(&metadata) != *executable {
                return Ok(true);
            }
            let current = fs::read(path).with_context(|| format!("reading {}", path.display()))?;
            Ok(&current != content)
        }
    }
}

pub fn write_entry(path: &Path, entry: &Entry) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    if let Ok(metadata) = fs::symlink_metadata(path) {
        if metadata.is_dir() {
            fs::remove_dir_all(path)
                .with_context(|| format!("replacing directory {}", path.display()))?;
        } else {
            fs::remove_file(path).with_context(|| format!("replacing {}", path.display()))?;
        }
    }
    match entry {
        Entry::Symlink { target } => create_symlink(target, path),
        Entry::File {
            content,
            executable,
        } => {
            fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
            set_executable(path, *executable)
        }
    }
}

/// Files under the managed roots that the plan does not contain.
fn stale_paths(
    root: &Path,
    managed_roots: &[String],
    plan: &BTreeMap<String, PlannedEntry>,
) -> Result<BTreeSet<String>> {
    let mut stale = BTreeSet::new();
    for managed in managed_roots {
        let directory = root.join(managed);
        if !directory.is_dir() {
            continue;
        }
        let walker = WalkDir::new(&directory)
            .follow_links(false)
            .into_iter()
            .filter_entry(|entry| {
                entry
                    .file_name()
                    .to_str()
                    .is_none_or(|name| !PRESERVED_NAMES.contains(&name))
            });
        for entry in walker {
            let entry = entry.with_context(|| format!("walking {}", directory.display()))?;
            if entry.file_type().is_dir() {
                continue;
            }
            let relative = entry
                .path()
                .strip_prefix(root)
                .context("walked outside the Neutron root")?
                .to_str()
                .context("non-UTF-8 path in a managed directory")?
                .replace('\\', "/");
            if !plan.contains_key(&relative) {
                stale.insert(relative);
            }
        }
    }
    Ok(stale)
}

fn remove_empty_directories(directory: &Path) -> Result<()> {
    if !directory.is_dir() {
        return Ok(());
    }
    for entry in WalkDir::new(directory)
        .contents_first(true)
        .follow_links(false)
    {
        let entry = entry.with_context(|| format!("walking {}", directory.display()))?;
        if entry.file_type().is_dir() && entry.path() != directory {
            let is_empty = fs::read_dir(entry.path())
                .with_context(|| format!("reading {}", entry.path().display()))?
                .next()
                .is_none();
            if is_empty {
                fs::remove_dir(entry.path()).with_context(|| {
                    format!("removing empty directory {}", entry.path().display())
                })?;
            }
        }
    }
    Ok(())
}

#[cfg(unix)]
pub fn is_executable(metadata: &fs::Metadata) -> bool {
    use std::os::unix::fs::PermissionsExt as _;
    metadata.permissions().mode() & 0o111 != 0
}

#[cfg(not(unix))]
pub fn is_executable(_metadata: &fs::Metadata) -> bool {
    false
}

#[cfg(unix)]
fn set_executable(path: &Path, executable: bool) -> Result<()> {
    use std::os::unix::fs::PermissionsExt as _;
    let mode = if executable { 0o755 } else { 0o644 };
    fs::set_permissions(path, fs::Permissions::from_mode(mode))
        .with_context(|| format!("setting permissions of {}", path.display()))
}

#[cfg(not(unix))]
fn set_executable(_path: &Path, _executable: bool) -> Result<()> {
    Ok(())
}

#[cfg(unix)]
fn create_symlink(target: &str, path: &Path) -> Result<()> {
    std::os::unix::fs::symlink(target, path)
        .with_context(|| format!("creating symlink {} -> {target}", path.display()))
}

#[cfg(not(unix))]
fn create_symlink(target: &str, path: &Path) -> Result<()> {
    bail!(
        "cannot create symlink {} -> {target}: run `cargo neutron sync` on macOS or Linux",
        path.display()
    )
}
